import { launch, sleep } from "./lib.mjs";
import path from "node:path";
const URL = "http://127.0.0.1:8767/", out = process.argv[2];
const b = await launch();
const snap = async (name, w, h, y, lang) => {
  const ctx = await b.newContext({ viewport: { width: w, height: h }, locale: lang === "de" ? "de-DE" : "en-GB", deviceScaleFactor: 1 });
  const p = await ctx.newPage();
  await p.goto(URL, { waitUntil: "load" }); await sleep(900);
  await p.evaluate((y) => { document.documentElement.style.scrollBehavior = "auto"; window.scrollTo(0, typeof y === "string" ? document.querySelector(y).offsetTop - 60 : y); }, y);
  await sleep(500);
  await p.screenshot({ path: path.join(out, name + ".png") });
  await ctx.close();
};
await snap("1-desktop-hero", 1440, 900, 0, "en");
await snap("2-desktop-architecture", 1440, 900, "#architecture", "en");
await snap("3-desktop-capabilities", 1440, 900, "#capabilities", "en");
await snap("4-desktop-closing", 1440, 900, 1e6, "en");
await snap("5-mobile-hero", 390, 844, 0, "en");
await snap("6-mobile-architecture", 390, 844, "#architecture", "en");
await b.close();
console.log("done");
