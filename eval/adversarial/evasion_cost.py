def doc_table(res: dict) -> str:
    """The cost vector as a markdown table. The header deliberately does NOT start
    with '| Rule |' -- tools/check_lane_coverage.py reads any such table as the
    rule scorecard and would union its first column into the covered rules."""
    head = ("| Rule-set (key) | Rules | Forgone events | Extra seconds | Stealth ev/s | Min keys | "
            "Joint frontier | Respelling | Forgery | Clock | Production reachable |")
    lines = [head, "|" + "---|" * 11]
    for key, r in sorted(res["rule_sets"].items()):
        mk = ", ".join(f"{k}={v['value']}" for k, v in sorted(r["min_keys"].items())) or "n/a"
        jf = r.get("joint_frontier")
        jtxt = "n/a" if jf is None else "/".join(f"({','.join(map(str, p))})" for p in jf["frontier"]) or "none<=6"
        sched = r.get("schedule") or {}
        lines.append("| " + " | ".join([
            f"`{key}`", ", ".join(f"`{n}`" for n in r["rules"]),
            str(r["forgone_events"]["value"]),
            str(sched.get("extra_seconds", "n/a")),
            str(sched.get("sustained_events_per_second", "n/a")),
            mk, jtxt,
            "evades" if r["respelling_evades"] else "no", "evades" if r["forgery_evades"] else "no",
            "forgeable" if r["clock_forgeable"] else "no",
            "yes" if r["production_reachable"] else "NO (sample map)"]) + " |")
    return "\n".join(lines)


def doc_block(res: dict) -> str:
    return (f"{DOC_BEGIN}\n"
            "Harness-measured on the bundled reference bursts (seed 7, deque counter backend). A vector, "
            "never a scalar: \"min keys\" is the fewest distinct keys of that kind that evade (`immune` = a "
            "companion rule on another kind still detects); the frontier is the Pareto-minimal joint key counts "
            "over a grid. `Respelling` / `Forgery` / `Clock` are open findings (see `eval/adversarial/"
            "evasion_findings.yaml`); they rest on security-judgement tables that are not yet ratified.\n\n"
            f"{doc_table(res)}\n{DOC_END}")


def _doc_text() -> str:
    return COVERAGE_DOC.read_text(encoding="utf-8")


def write_doc(res: dict, path=None) -> bool:
    p = Path(path) if path is not None else COVERAGE_DOC
    text = p.read_text(encoding="utf-8")
    crlf = "\r\n" in text
    text = text.replace("\r\n", "\n")
    block = doc_block(res)
    if DOC_BEGIN in text and DOC_END in text:
        a, b = text.index(DOC_BEGIN), text.index(DOC_END) + len(DOC_END)
        new = text[:a] + block + text[b:]
    else:
        new = (text.rstrip("\n") + "\n\n## Evasion cost (generated)\n\n" + block + "\n")
    if crlf:
        new = new.replace("\n", "\r\n")
    changed = new != text.replace("\n", "\r\n" if crlf else "\n")
    p.write_text(new, encoding="utf-8", newline="")
    return changed


def check_doc(res: dict, path=None) -> str | None:
    p = Path(path) if path is not None else COVERAGE_DOC
    text = p.read_text(encoding="utf-8").replace("\r\n", "\n")
    if DOC_BEGIN not in text or DOC_END not in text:
        return "contracts/detection-coverage.md has no generated evasion-cost block (run --write-doc)"
    a, b = text.index(DOC_BEGIN), text.index(DOC_END) + len(DOC_END)
    if text[a:b] != doc_block(res):
        return "the generated evasion-cost table in contracts/detection-coverage.md is stale (run --write-doc)"
    return None


