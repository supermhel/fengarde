def _print_vector(res: dict) -> None:
    print("== evasion cost vector (harness-measured, seed %s, deque backend) ==" % res["seed"])
    print(f"  {'rule-set':<34}{'loss':>6}{'extra_s':>11}{'stealth':>10}  min_keys / joint frontier")
    for key, r in sorted(res["rule_sets"].items()):
        s = r.get("schedule") or {}
        mk = " ".join(f"{k}={v['value']}" for k, v in sorted(r["min_keys"].items())) or "-"
        jf = r.get("joint_frontier")
        jtxt = "" if jf is None else "  joint=" + "/".join(f"({','.join(map(str, p))})" for p in jf["frontier"])
        flags = "".join(c for c, f in (("R", r["respelling_evades"]), ("F", r["forgery_evades"]),
                                        ("C", r["clock_forgeable"])) if f)
        print(f"  {key:<34}{str(r['forgone_events']['value']):>6}{str(s.get('extra_seconds', '-')):>11}"
              f"{str(s.get('sustained_events_per_second', '-')):>10}  {mk}{jtxt}"
              f"{'  [' + flags + ']' if flags else ''}"
              f"{'' if r['production_reachable'] else '  (sample map: not production reachable)'}")


def main(argv: list | None = None) -> int:
    ap = argparse.ArgumentParser(prog="evasion_cost")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--rules-dir", type=Path, default=None, help="measure a (mutated) COPY of contracts/rules")
    ap.add_argument("--floor", type=Path, default=FLOOR_PATH)
    ap.add_argument("--findings", type=Path, default=FINDINGS_PATH)
    ap.add_argument("--tables", type=Path, default=None)
    ap.add_argument("--out", type=Path, default=OUT_PATH)
    ap.add_argument("--rule-set", action="append", default=None)
    ap.add_argument("--update-floor", action="store_true")
    ap.add_argument("--allow-lower", action="store_true")
    ap.add_argument("--reason", default=None)
    ap.add_argument("--write-doc", action="store_true")
    ap.add_argument("--no-doc-check", action="store_true")
    args = ap.parse_args(argv)

    tables = ax.load_tables(args.tables)
    res = measure(args.seed, args.rules_dir, tables, only=args.rule_set)
    floor, findings = load_floor(args.floor), load_findings(args.findings)
    _print_vector(res)

    if args.update_floor:
        if args.allow_lower and not args.reason:
            print("[FAIL] --allow-lower needs --reason")
            return 2
        new, refused = update_floor(res, floor, findings, allow_lower=args.allow_lower, reason=args.reason)
        if refused:
            for m in refused:
                print(f"[REFUSED] {m}")
            print("[FAIL] the ratchet only moves toward the defender; lowering needs "
                  "--update-floor --allow-lower --reason '<why>' (recorded as a dated 'lowered:' entry)")
            return 1
        args.floor.write_text("# evasion_floor.yaml -- GENERATED by evasion_cost.py --update-floor. The ratchet: values "
                              "only move toward the defender.\n# Lowering needs --allow-lower --reason (appends a dated "
                              "'lowered:' entry). Hand edits are reverted by the next check.\n"
                              + yaml.safe_dump(new, sort_keys=True, default_flow_style=False), encoding="utf-8")
        print(f"[OK] floor written -> {args.floor}")
        floor = new

    gate = check(res, floor, findings)
    doc_problem = None
    if args.write_doc:
        write_doc(res)
        print("[OK] generated table written to contracts/detection-coverage.md")
    elif not args.no_doc_check and args.rules_dir is None and not args.rule_set:
        doc_problem = check_doc(res)
        if doc_problem:
            gate.fail.append(f"DOC {doc_problem}")
    open_bugs = [f for f in findings if f.get("class") == "BUG" and f.get("status") == "open"]
    out = dict(res)
    out["gate"] = gate.as_dict()
    out["open_bugs"] = [f["id"] for f in open_bugs]
    out["open_findings"] = [f["id"] for f in findings]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(out, indent=2, sort_keys=True), encoding="utf-8")
    for m in gate.info:
        print(f"[INFO] {m}")
    for m in gate.warn:
        print(f"[WARN] {m}")
    for m in gate.fail:
        print(f"[FAIL] {m}")
    print(f"open BUG findings: {len(open_bugs)} ({', '.join(f['id'] for f in open_bugs) or 'none'}); "
          f"unratified table rows: {res['tables_ratified']['rows'] - res['tables_ratified']['ratified']}"
          f"/{res['tables_ratified']['rows']}")
    print(f"-> {args.out}")
    if gate.fail:
        print(f"[FAIL] {len(gate.fail)} evasion-cost gate failure(s)")
        return 1
    print("[OK] evasion-cost floor, findings register and coverage hold")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
