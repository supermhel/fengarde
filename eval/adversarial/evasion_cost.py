def _num(v):
    """None / 'immune' -> the top of every ordering."""
    if v is None or v == IMMUNE:
        return _INF
    if isinstance(v, bool):
        return int(v)
    return v


def measure_set(probe: ps.FastProbe, rs: ax.RuleSet, burst: ax.Burst, tables: dict) -> dict:
    """The cost vector of one rule-set on its reference burst."""
    lab = ax.Lab(probe, rs, burst)
    row: dict = {"key": rs.key, "rules": rs.names, "basis": "harness-measured", "burst_source": burst.source,
                 "burst_events": burst.n, "production_reachable": burst.production_reachable,
                 "reachability_basis": burst.reachability_basis, "orphan_companion": rs.orphan,
                 "fingerprint": rs.fingerprint(), "params": rs.params()}
    agree = True

    loss = ax.search_loss(lab)
    row["forgone_events"] = {"value": loss["forgone_events"] if loss["forgone_events"] is not None else IMMUNE,
                             "predicted": loss["predicted"] if loss["predicted"] is not None else IMMUNE,
                             "agree": loss["agree"]}
    agree &= loss["agree"]

    sched = ax.search_schedule(lab)
    row["schedule"] = sched
    agree &= bool(sched.get("agree", True))

    # --- key spread -----------------------------------------------------
    searchable, unsearchable = [], []
    for r in rs.rules:
        kind = r.kind
        if kind is None:
            unsearchable.append({"group_by": r.group_by, "reason": "group_by is not in KEY_KINDS"})
        elif kind not in lab.burst.setters:
            unsearchable.append({"group_by": r.group_by, "reason": f"no setter for kind '{kind}' on this burst"})
        elif kind not in searchable:
            vs = ax.verify_setter(lab, kind)
            if vs.get("distinct", 0) < 2:
                unsearchable.append({"group_by": r.group_by, "reason": f"setter for '{kind}' does not move the key "
                                                                         f"(verify-by-parse: {vs})"})
            else:
                searchable.append(kind)
    row["unsearchable_keys"] = unsearchable
    row["min_keys"] = {}
    for kind in searchable:
        sp = ax.search_spread(lab, kind)
        row["min_keys"][kind] = {"value": sp["min_keys"], "predicted": sp["predicted"], "agree": sp["agree"]}
        agree &= sp["agree"]
    if len(searchable) >= 2:
        jf = ax.search_joint(lab, searchable[:3])
        row["joint_frontier"] = jf
        agree &= jf["agree"]
    else:
        row["joint_frontier"] = None

    if rs.periodic:
        jit = ax.search_jitter(lab)
        row["jitter"] = jit
        agree &= jit["agree"]

    # --- obfuscation / forgery / clock ----------------------------------
    resp = ax.respelling_axis(lab, tables)
    row["respelling"] = resp
    row["respelling_evades"] = bool(resp["respelling_evades"])
    row["respelling_evades_ratified"] = any(
        o["class"] == "BUG" and o["ratified"] and o["control_split_without_respelling_detected"]
        for o in resp["ops"])
    agree &= all(o["agree"] for o in resp["ops"])
    forg = ax.forgery_axis(lab, tables)
    row["forgery"] = forg
    row["forgery_evades"] = bool(forg.get("forgery_evades"))
    row["forgery_evades_ratified"] = bool(forg.get("forgery_evades")) and bool(forg.get("ratified"))
    agree &= bool(forg.get("agree", True))
    clk = ax.clock_forgeable(lab)
    row["clock"] = clk
    row["clock_forgeable"] = bool(clk["clock_forgeable"])
    row["clock_forgeable_ratified"] = False      # no table row exists for the clock-trust question yet
    row["agree"] = bool(agree)
    return row


def measure(seed: int = 7, rules_dir=None, tables: dict | None = None, *, probe: ps.FastProbe | None = None,
            only: list | None = None) -> dict:
    tables = tables if tables is not None else ax.load_tables()
    sets = ax.build_rule_sets(rules_dir)
    probe = probe or ps.FastProbe(rules_dir=rules_dir, strict_clock=True)
    rows: dict = {}
    no_burst: list = []
    for key, rs in sets.items():
        if only and key not in only:
            continue
        burst = ax.reference_burst(key, seed)
        if burst is None:
            no_burst.append(key)
            continue
        rows[key] = measure_set(probe, rs, burst, tables)
    return {"seed": seed, "basis": "harness-measured", "backend": "deque", "rule_sets": rows,
            "no_reference_burst": sorted(no_burst), "stateful_rule_sets": sorted(sets),
            "tables_ratified": _tables_ratified(tables)}


def _tables_ratified(tables: dict) -> dict:
    rows = [r for sec in ("attacker_control", "identity") for r in (tables.get(sec) or {}).values()]
    return {"rows": len(rows), "ratified": sum(1 for r in rows if r.get("ratified"))}


