# Floor update (the ratchet)
# ===========================================================================
def update_floor(res: dict, floor: dict, findings: list, *, allow_lower: bool = False, reason: str | None = None,
                 today: str | None = None) -> tuple:
    """Return (new_floor, refused). Floors only move toward the defender; a
    change that would LOWER one is refused unless ``allow_lower`` and a reason."""
    today = today or datetime.date.today().isoformat()
    new = copy.deepcopy(floor)
    new.setdefault("version", 1)
    new.setdefault("rule_sets", {})
    new.setdefault("waivers", {})
    refused: list = []
    open_for: dict = {}
    for f in findings:
        if f.get("status") == "open" and f.get("repro", {}).get("flag"):
            for k in f.get("rule_sets") or []:
                open_for[(k, f["repro"]["flag"])] = f["id"]
    for key, r in sorted(res["rule_sets"].items()):
        fl = new["rule_sets"].setdefault(key, {"fields": {}})
        fl.setdefault("fields", {})
        fl["production_reachable"] = r["production_reachable"]
        old_fp = fl.get("fingerprint")
        refused_before = len(refused)
        for name, (val, better) in field_values(r).items():
            cur = fl["fields"].get(name)
            of = open_for.get((key, name))
            entry = {"better": better, "value": val, "basis": "harness-measured"}
            if name in TABLE_FIELDS and of:
                entry["open_finding"] = of
            if cur is None:
                fl["fields"][name] = entry
            elif _worse(better, val, cur["value"]):
                if not (allow_lower and reason):
                    refused.append(f"{key}.{name}: measured {val} is worse than floor {cur['value']}")
                    continue
                fl.setdefault("lowered", []).append({"date": today, "field": name, "from": cur["value"],
                                                     "to": val, "reason": reason})
                fl["fields"][name] = entry
            else:
                fl["fields"][name] = entry          # improved or equal: ratchet up
        for name in sorted(set(fl["fields"]) - set(field_values(r))):
            if allow_lower and reason:
                fl.setdefault("lowered", []).append({"date": today, "field": name, "from": fl["fields"][name]["value"],
                                                     "to": "not measured", "reason": reason})
                del fl["fields"][name]
            else:
                refused.append(f"{key}.{name}: no longer measured (an axis disappeared)")
        jf = r.get("joint_frontier")
        if jf is not None:
            old = fl.get("joint_frontier")
            if old is None or not frontier_regressed(old["frontier"], jf["frontier"]):
                fl["joint_frontier"] = {"kinds": jf["kinds"], "frontier": jf["frontier"], "grid_max": jf["grid_max"],
                                        "basis": "harness-measured"}
            elif allow_lower and reason:
                fl.setdefault("lowered", []).append({"date": today, "field": "joint_frontier", "from": old["frontier"],
                                                     "to": jf["frontier"], "reason": reason})
                fl["joint_frontier"] = {"kinds": jf["kinds"], "frontier": jf["frontier"], "grid_max": jf["grid_max"],
                                        "basis": "harness-measured"}
            else:
                refused.append(f"{key}.joint_frontier: measured {jf['frontier']} evades with fewer keys than {old['frontier']}")
        if old_fp != r["fingerprint"]:
            if len(refused) == refused_before:
                fl["fingerprint"] = r["fingerprint"]
                fl["params"] = r["params"]
    # a floor for a rule-set that no longer exists
    for key in sorted(set(new["rule_sets"]) - set(res["rule_sets"])):
        if key in res["stateful_rule_sets"]:
            continue                                  # waived, keep
        if allow_lower and reason:
            new.setdefault("removed", []).append({"date": today, "rule_set": key, "reason": reason})
            del new["rule_sets"][key]
        else:
            refused.append(f"{key}: floor exists but the rule-set is gone (removed rule or companion?)")
    return new, refused


