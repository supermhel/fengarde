"""evasion_cost -- the per-rule EVASION COST VECTOR, its published floor, and the
register of known findings.

WHY THIS EXISTS (2026-10-02)
    ``evasion_search`` answers "can a burst still be detected after one
    perturbation?" for four axes and six steps. This module answers the question a
    defender actually has -- "what does it COST to get past this rule?" -- for
    every stateful rule-set, as a VECTOR (several incommensurable numbers; a
    weighted sum would invent an exchange rate between addresses and seconds):

        forgone_events        events the attacker must give up                (linear scan)
        extra_seconds         time the OPTIMAL slow schedule adds             (exact, greedy)
        stealth_rate          events/s/key sustainable forever below threshold
        min_keys[kind]        fewest addresses / accounts / domains ...; "immune" when a
                              companion rule on another kind still sees the burst
        joint_frontier        Pareto-minimal (a, b) key counts over a grid, cell by cell
                              against an independent prediction
        respelling_evades     an identity-PRESERVING respelling evades            (F2)
        forgery_evades        a forged attribution evades                        (F3)
        clock_forgeable       forging only the record clock evades               (F4)

    Every measured number carries an independent prediction (``evasion_axes.predict_*``)
    and an ``agree`` flag; a disagreement fails the gate. Everything is tagged
    ``basis: harness-measured``.

THE FLOOR (``evasion_floor.yaml``)
    The first measurement is committed as a floor and may only move in the
    DEFENDER's favour. Each field carries ``better: min|max`` (stealth rate: lower is
    better; keys, seconds, events: higher). A measured value worse than its floor, a
    changed rule parameter / selection / allowlist without a floor refresh (the
    fingerprint), a vanished companion, a stale floor and an uncovered stateful rule
    all FAIL, naming the rule, axis, measured value and floor. Lowering a floor needs
    ``--update-floor --allow-lower --reason ...`` and appends a dated ``lowered:``
    entry -- a legitimate false-positive tune is therefore a deliberate, recorded act
    (intended friction).

THE FINDINGS REGISTER (``evasion_findings.yaml``)
    A closed list of the evasions this lane knows about (the same pattern as
    ``eval/twin/oracle_consistency._ACCEPTED``). An evasion NOT in the register FAILS;
    a registered finding that no longer reproduces is STALE and FAILS until the entry is
    deleted; an open BUG passes but is printed and counted in the artifact (honest
    status, not a green wash). A boolean floor whose measured value is True is
    tolerated only through ``open_finding: <id>``.

    Judgement-dependent classes (respelling, forgery, clock) are decided by
    ``evasion_tables.yaml`` rows that are all ``ratified: false`` today: a finding
    that rests only on unratified rows is reported as INFO/WARN and does not turn the
    gate red until the owner ratifies the table.

STDLIB + PyYAML. Deterministic; the JSON is a pure function of (rules, seed).
"""
