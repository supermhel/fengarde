def field_values(row: dict) -> dict:
    """name -> (value, better). The scalar fields a floor can hold."""
    out = {"forgone_events": (row["forgone_events"]["value"], "max")}
    sched = row.get("schedule") or {}
    if sched.get("extra_seconds") is not None:
        out["extra_seconds"] = (sched["extra_seconds"], "max")
    if sched.get("sustained_events_per_second") is not None:
        out["stealth_rate"] = (sched["sustained_events_per_second"], "min")
    for kind, v in sorted(row["min_keys"].items()):
        out[f"min_keys.{kind}"] = (v["value"], "max")
    for name in TABLE_FIELDS:
        out[name] = (bool(row[name]), "min")
    return out


def frontier_regressed(floor_frontier: list, measured_frontier: list) -> list:
    """Measured frontier points that are NOT dominated by (componentwise >=) some
    floor point: the attacker evades with fewer keys than the floor allows."""
    return [m for m in measured_frontier
            if not any(all(m[i] >= f[i] for i in range(len(m))) for f in floor_frontier)]


def load_floor(path=None) -> dict:
    p = Path(path) if path is not None else FLOOR_PATH
    if not p.exists():
        return {"version": 1, "rule_sets": {}, "waivers": {}}
    return yaml.safe_load(p.read_text(encoding="utf-8")) or {"version": 1, "rule_sets": {}, "waivers": {}}


def load_findings(path=None) -> list:
    p = Path(path) if path is not None else FINDINGS_PATH
    if not p.exists():
        return []
    return (yaml.safe_load(p.read_text(encoding="utf-8")) or {}).get("findings") or []


def _worse(better: str, measured, floor) -> bool:
    m, f = _num(measured), _num(floor)
    return m < f if better == "max" else m > f


def _fmt(v) -> str:
    return IMMUNE if v == _INF else str(v)


# ===========================================================================
# Gate
# ===========================================================================
class Gate:
    def __init__(self) -> None:
        self.fail: list = []
        self.warn: list = []
        self.info: list = []

    def as_dict(self) -> dict:
        return {"fail": self.fail, "warn": self.warn, "info": self.info}


def finding_reproduces(f: dict, res: dict) -> tuple:
    """(reproduces, affected rule-sets) for a registered finding. Table-derived
    findings read the measured rows; F1 reads the counter primitive."""
    kind = f.get("repro", {}).get("kind")
    if kind == "noise_primitive":
        return nd.f1_reproduces(), []
    flag = f.get("repro", {}).get("flag")
    affected = sorted(k for k, r in res["rule_sets"].items() if r.get(flag))
    return bool(affected), affected


def check(res: dict, floor: dict, findings: list, *, strict_coverage: bool = True) -> Gate:
    g = Gate()
    rows = res["rule_sets"]
    waivers = floor.get("waivers") or {}

    # -- coverage: every stateful rule-set has a row or a dated waiver --------
    for key in res["stateful_rule_sets"]:
        if key in rows:
            continue
        w = waivers.get(key)
        if w and w.get("reason") and w.get("date"):
            g.info.append(f"coverage: {key} waived ({w['date']}): {w['reason']}")
        else:
            g.fail.append(f"COVERAGE {key}: stateful rule-set has neither a reference burst (storyline or "
                          f"rule_probes template) nor a dated waiver in evasion_floor.yaml")
    for key, r in rows.items():
        for u in r["unsearchable_keys"]:
            w = waivers.get(f"{key}:{u['group_by']}")
            if w and w.get("reason") and w.get("date"):
                g.info.append(f"coverage: {key} key {u['group_by']} waived ({w['date']})")
            else:
                g.fail.append(f"COVERAGE {key}: unsearchable key {u['group_by']} ({u['reason']}) and no waiver")

    # -- prediction agreement --------------------------------------------------
    for key, r in rows.items():
        if not r["agree"]:
            g.fail.append(f"DISAGREE {key}: a measured number differs from the independent prediction "
                          f"(a bug in the pipeline OR in the predictor -- see out/evasion_cost.latest.json)")

    # -- findings register -----------------------------------------------------
    by_id = {f["id"]: f for f in findings}
    covered: dict = {}                       # flag -> set of rule-sets listed by an open finding
    for f in findings:
        repro, affected = finding_reproduces(f, res)
        listed = set(f.get("rule_sets") or [])
        flag = f.get("repro", {}).get("flag")
        if f.get("status") != "open":
            g.fail.append(f"FINDING {f['id']}: status '{f.get('status')}' -- only open findings may stay in the "
                          f"register; delete a fixed entry")
            continue
        if not repro:
            g.fail.append(f"STALE {f['id']}: registered {f['class']} no longer reproduces -- delete the entry "
                          f"(and flip the floors that name it to false with --update-floor)")
            continue
        if flag:
            for k in sorted(listed - set(affected)):
                if k in rows:
                    g.fail.append(f"STALE {f['id']}: rule-set {k} is listed but '{flag}' is no longer true there")
            covered.setdefault(flag, set()).update(listed)
        brief = " ".join(str(f.get("summary", "")).split())
        g.info.append(f"OPEN {f['class']} {f['id']}: {brief[:150]}{'...' if len(brief) > 150 else ''}"
                      + (f" [{', '.join(affected)}]" if affected else ""))
    for flag in TABLE_FIELDS:
        for key, r in sorted(rows.items()):
            if r.get(flag) and key not in covered.get(flag, set()):
                msg = f"UNLISTED {flag} on {key}: not in evasion_findings.yaml"
                (g.fail if r.get(flag + "_ratified") else g.warn).append(
                    msg + ("" if r.get(flag + "_ratified") else " (rests on unratified table rows: not gating)"))

    # -- floors ----------------------------------------------------------------
    floors = floor.get("rule_sets") or {}
    for key, fl in sorted(floors.items()):
        if key not in rows:
            if key in waivers or key not in res["stateful_rule_sets"]:
                g.fail.append(f"FLOOR {key}: a floor exists for a rule-set that is no longer measured "
                              f"(rule or companion removed?) -- a deliberate refresh needs "
                              f"--update-floor --allow-lower --reason ...")
            continue
    for key, r in sorted(rows.items()):
        fl = floors.get(key)
        if fl is None:
            g.fail.append(f"FLOOR {key}: no floor recorded -- run --update-floor once and commit evasion_floor.yaml")
            continue
        if fl.get("fingerprint") != r["fingerprint"]:
            g.fail.append(f"FINGERPRINT {key}: the rule parameters / selection / allowlists changed since the floor "
                          f"was recorded -- re-measure and refresh deliberately (--update-floor)")
        cur = field_values(r)
        for name, spec in sorted((fl.get("fields") or {}).items()):
            better = spec.get("better", "max")
            if name not in cur:
                g.fail.append(f"FLOOR {key}.{name}: recorded in the floor but not measured now "
                              f"(axis lost: e.g. a companion or key kind disappeared)")
                continue
            val = cur[name][0]
            if not _worse(better, val, spec["value"]):
                continue
            if name in TABLE_FIELDS:
                of = spec.get("open_finding")
                if of and of in by_id and val is True:
                    continue                       # tolerated through an open finding
                lvl = g.fail if r.get(name + "_ratified") else g.warn
                lvl.append(f"FLOOR {key}.{name}: measured {_fmt(_num(val))} is worse than floor {spec['value']}"
                           + ("" if r.get(name + "_ratified") else " (unratified table rows: not gating)"))
                continue
            g.fail.append(f"FLOOR {key}.{name}: measured {_fmt(_num(val))} is worse than the floor "
                          f"{_fmt(_num(spec['value']))} (better={better}) -- the rule got cheaper to evade")
        for name in sorted(set(cur) - set((fl.get("fields") or {}))):
            g.info.append(f"FLOOR {key}.{name}: measured {cur[name][0]} but no floor field yet (--update-floor)")
        jf, fjf = r.get("joint_frontier"), fl.get("joint_frontier")
        if jf is not None and fjf is not None:
            bad = frontier_regressed(fjf["frontier"], jf["frontier"])
            if bad:
                g.fail.append(f"FLOOR {key}.joint_frontier: measured frontier point(s) {bad} evade with fewer keys "
                              f"than the floor frontier {fjf['frontier']} allows")
        elif jf is None and fjf is not None:
            g.fail.append(f"FLOOR {key}.joint_frontier: recorded in the floor but not measured now (an axis lost)")
    return g


