# Build
# ---------------------------------------------------------------------------
def _expected_rules(oracle: dict, step: str) -> set:
    pt = (oracle.get("detection_points") or {}).get(step) or {}
    return {r.get("rule_id") for r in (pt.get("expected_rules") or [])}


def build(artefact: dict, rules: dict, oracles: dict) -> dict:
    """The matrix as plain data. ``artefact`` is a ``scenario_matrix.run_all`` result (its per-scenario
    ``baseline.fired_pairs`` and per-row ``fired_pairs`` / ``applicable``), ``rules`` is
    ``load_rule_infos()``, ``oracles`` is ``{scenario: oracle dict}``."""
    by_id = {r["id"]: r for r in rules.values()}
    scen = artefact["scenarios"]
    names = sorted(scen)

    per_rule = {stem: {"baseline": {}, "variants": {}, "cells": {}} for stem in rules}
    undetected = []
    disagreements = []
    for name in names:
        oracle = oracles[name]
        steps = set(oracle.get("expected_sequence") or [])
        deps = oracle.get("step_dependencies") or {}
        sm = scen[name]
        base_pairs = [tuple(p) for p in sm["baseline"].get("fired_pairs", [])]
        # (a) baseline: observed fires, attack steps only (decoy labels are not in expected_sequence)
        for step, rid in base_pairs:
            if step in steps and rid in by_id:
                per_rule[by_id[rid]["stem"]]["baseline"].setdefault(name, set()).add(step)
        # (b) variants: where each rule fires per applicable variant (companions are exercised here)
        rows = [r for r in sm["rows"] if r.get("applicable")]
        for r in rows:
            for step, rid in r.get("fired_pairs", []):
                if step in steps and rid in by_id:
                    per_rule[by_id[rid]["stem"]]["variants"].setdefault(name, set()).add(
                        f"{r['axis']}/{r['variant']}")
        # (c) survival cells
        for stem, info in rules.items():
            fired_steps = sorted(per_rule[stem]["baseline"].get(name, ()))
            if not fired_steps:
                continue
            group = set(fired_steps)
            for s in fired_steps:
                group |= set(deps.get(s) or [])
            cells = {"survived": [], "evaded_declared": [], "evaded_unexpected": [], "excluded": []}
            for r in rows:
                key = f"{r['axis']}/{r['variant']}"
                if r["axis"] == "loss":
                    dropped = r["variant"][len("drop_"):]
                    if dropped in group:
                        cells["excluded"].append(key)          # own step / its context step
                        continue
                fired_here = {(s, rid) for s, rid in r.get("fired_pairs", [])}
                kept = any((s, info["id"]) in fired_here for s in group)
                if kept:
                    cells["survived"].append(key)
                    continue
                step_alerts = sorted({s for s, _rid in fired_here if s in fired_steps})
                entry = {"variant": key, "step_still_alerts": bool(step_alerts)}
                if (info["stem"], key) in KNOWN_CAUSES:
                    entry["known_cause"] = KNOWN_CAUSES[(info["stem"], key)]
                cls = "evaded_declared" if declared_evasion(info, r["axis"], r["variant"]) else "evaded_unexpected"
                cells[cls].append(entry)
            per_rule[stem]["cells"][name] = cells
        # (d) honest gaps and observed-vs-oracle disagreements
        for step, pt in sorted((oracle.get("detection_points") or {}).items()):
            gap = pt.get("gap") or {}
            if gap.get("no_rule_exists") and not pt.get("context") and gap.get("attack_technique"):
                undetected.append({"scenario": name, "step": step, "technique": gap["attack_technique"],
                                   "reason": " ".join(str(gap.get("reason", "")).split())})
        fired_by_step = {}
        for step, rid in base_pairs:
            fired_by_step.setdefault(step, set()).add(rid)
        for step in sorted(steps):
            exp = _expected_rules(oracle, step)
            obs = fired_by_step.get(step, set())
            for rid in sorted(exp - obs):
                rule = by_id.get(rid)
                if rule and rule.get("companion_of") and by_id_id_in(rule["companion_of"], obs):
                    continue                                    # silent by design: its sibling alerted
                disagreements.append({"scenario": name, "step": step, "rule": (rule or {}).get("stem", rid),
                                      "kind": "oracle_expects_but_baseline_silent"})
            declared_gap = bool(((oracle.get("detection_points") or {}).get(step) or {}).get("gap", {})
                                .get("no_rule_exists"))
            for rid in sorted(obs - exp):
                if exp or declared_gap:
                    disagreements.append({"scenario": name, "step": step,
                                          "rule": (by_id.get(rid) or {}).get("stem", rid),
                                          "kind": "baseline_fires_but_oracle_does_not_declare"})

    rule_rows = {}
    for stem, info in sorted(rules.items()):
        pr = per_rule[stem]
        baseline = {k: sorted(v) for k, v in sorted(pr["baseline"].items())}
        variants = {k: sorted(v) for k, v in sorted(pr["variants"].items())}
        exercised_by_baseline = bool(baseline)
        exercised_by_companion_variant = bool(info.get("companion_of") and variants)
        rule_rows[stem] = {
            "id": info["id"], "framework": info["framework"], "technique": info["technique"],
            "tactic": info["tactic"], "companion_of": info.get("companion_of"),
            "rule_exists": True,
            "fires_on_storyline": baseline,
            "fires_in_variants": variants if info.get("companion_of") else {},
            "exercised": exercised_by_baseline or exercised_by_companion_variant,
            "exercised_via": ("baseline" if exercised_by_baseline else
                              "companion_variant" if exercised_by_companion_variant else None),
            "survives_mutation": pr["cells"],
        }

    techniques: dict = {}
    for stem, rr in rule_rows.items():
        if not rr["technique"]:
            continue
        key = f"{rr['framework']}:{rr['technique']}"
        t = techniques.setdefault(key, {"framework": rr["framework"], "technique": rr["technique"],
                                        "tactic": rr["tactic"], "rule_exists": True, "rules": [],
                                        "fires_on_storyline": [], "exercised": False,
                                        "survived": 0, "evaded_declared": 0, "evaded_unexpected": 0})
        t["rules"].append(stem)
        if rr["exercised"]:
            t["exercised"] = True
        for sc, steps_ in rr["fires_on_storyline"].items():
            t["fires_on_storyline"] += [f"{sc}:{s}" for s in steps_]
        for sc, cells in rr["survives_mutation"].items():
            t["survived"] += len(cells["survived"])
            t["evaded_declared"] += len(cells["evaded_declared"])
            t["evaded_unexpected"] += len(cells["evaded_unexpected"])
    for t in techniques.values():
        t["rules"] = sorted(t["rules"])
        t["fires_on_storyline"] = sorted(set(t["fires_on_storyline"]))

    return {
        "basis": "harness-measured",
        "seed": artefact.get("seed"),
        "scenario_list": list(artefact.get("scenario_list") or []),
        "inputs_fingerprint": artefact.get("inputs_fingerprint"),
        "rules": rule_rows,
        "techniques": dict(sorted(techniques.items())),
        "demonstrated_but_undetected": sorted(undetected, key=lambda u: (u["technique"], u["scenario"], u["step"])),
        "observed_vs_oracle": sorted(disagreements, key=lambda d: (d["scenario"], d["step"], d["rule"], d["kind"])),
        "notes": [
            "survives_mutation excludes loss/drop_<own or context step> and variants that changed no event",
            "evaded_declared = an evasion the rule's own YAML predicts; evaded_unexpected = anything else",
            "no survival ratchet here: the per-technique survival baseline belongs to the ratchet step",
        ],
    }


def by_id_id_in(rule_id: str, observed: set) -> bool:
    return rule_id in observed


