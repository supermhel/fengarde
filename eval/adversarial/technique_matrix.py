def load_rule_infos(rules_dir: Path = RULES_DIR) -> dict:
    """``{file_stem: info}``. ``info`` carries what the survival classification needs; the technique
    comes from the rule's ``mitre:`` block exactly as ``coverage_layer`` reads it."""
    out = {}
    for f in sorted(Path(rules_dir).glob("*.yml")):
        d = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        if not isinstance(d, dict) or not d.get("id"):
            continue
        mitre = d.get("mitre") if isinstance(d.get("mitre"), dict) else None
        siem = d.get("siem") or {}
        out[f.stem] = {
            "stem": f.stem,
            "id": d["id"],
            "title": d.get("title"),
            "framework": (mitre or {}).get("framework", "attack") if mitre else None,
            "technique": (mitre or {}).get("technique") if mitre else None,
            "tactic": (mitre or {}).get("tactic") if mitre else None,
            "threshold": siem.get("threshold"),
            "window_seconds": siem.get("window_seconds"),
            "group_by": siem.get("group_by"),
            "distinct_field": siem.get("distinct_field"),
            "companion_of": siem.get("companion_of"),
            "periodic": bool(siem.get("periodicity")),
            "outside_hours": "outside_hours" in json.dumps(d.get("detection") or {}),
        }
    return out


def declared_evasion(rule: dict, axis: str, variant: str) -> bool:
    """Does the rule's OWN configuration predict that this variant evades it?

    Deliberately narrow: an evasion that no YAML predicts must stay ``evaded_unexpected``."""
    key = f"{axis}/{variant}"
    gb, df = rule.get("group_by"), rule.get("distinct_field")
    if axis in ("volume", "pacing") and (rule.get("threshold") or rule.get("periodic")):
        return True                      # thin it / slow it: any threshold or periodicity rule
    if axis == "distribution":
        ip_keyed = gb == "src_endpoint.ip" or df == "src_endpoint.ip"
        host_keyed = gb == "src_endpoint.hostname"
        if variant.startswith("ip_rotate") and ip_keyed:
            return True
        if variant == "hostname_rotate_all" and host_keyed:
            return True
    if axis == "identity" and gb == "actor.user.name":
        return True
    if key == "timing/to_business_hours" and rule.get("outside_hours"):
        return True
    return False


