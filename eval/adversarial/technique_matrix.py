"""technique_matrix -- the ATT&CK technique matrix, BUILT FROM CODE, plus the gate that keeps it honest.

WHY THIS EXISTS (2026-10-03)
    ``eval/attack/coverage_layer.py`` says what rules CLAIM (a ``mitre:`` block). ``fire_check.py`` says a
    rule fires on its own fixture. Neither says whether a technique is ever demonstrated END TO END by a
    storyline on the real parsers, or whether the detection survives a mutation. This matrix adds exactly
    those two columns, per (framework, technique) and per rule:

      rule_exists         a shipped rule declares the technique
      fires_on_storyline  where the rule fired in the BASELINE grade of a storyline (observed, not read
                          from the oracle). A COMPANION rule is silent at baseline BY DESIGN (the sibling
                          alerts first and the companion is dropped on the same event), so for companions
                          the cell is "fires in a mutation variant" instead.
      survives_mutation   per (rule, storyline): over the variants where the rule fired at baseline, each
                          is ``survived`` / ``evaded_declared`` / ``evaded_unexpected``. ``evaded_declared``
                          is an evasion the rule's OWN YAML predicts (threshold -> thinning/slowing; a
                          source-address key -> address rotation; an actor key -> account split; a
                          periodicity bound -> jitter; an outside_hours predicate -> moving into hours).
                          Everything else is ``evaded_unexpected``: a question, not necessarily a bug.

    It also lists "demonstrated but undetected": the techniques a storyline performs for which the oracle
    declares ``no_rule_exists`` (with the ATT&CK id) -- the honest missing-rule register.

WHAT IS EXCLUDED FROM survive / evade CELLS (and why)
    * ``loss/drop_<step>`` where ``<step>`` is a step the rule fired at (a log source going dark cannot be
      detected through: that is the lane's NEGATIVE CONTROL), or a step the rule's own step DEPENDS on
      (drop the victim's login and impossible travel is blind by design);
    * any variant that changed no event (``applicable=False``: "mutated nothing" is never a pass);
    * a rule that did not fire at baseline (nothing to survive).
    A rule re-attributed to a dependency step (impossible travel fires on whichever login arrives last) is
    credited to its step's dependency group, not scored as lost.

THE GATE (exit 1 on any problem)
    G1 the artefact is current:    seed == 7, scenario list == the whole registry, input fingerprint == the
                                   live tree (``out/`` is gitignored, so the file alone cannot say what it is)
    G2 every rule is exercised by at least one storyline (baseline fire; a companion may fire in a variant),
       or is on the DATED waiver list ``technique_waivers.yaml``. The list is closed and never silent.
    G3 every technique a rule declares is exercised by a rule that fired, or all its rules are waived
    G4 every rule carries a ``mitre:`` block or is on the permanent no-technique list
    G5 a waiver that no longer applies (the rule IS exercised / has a technique / is gone) FAILS as stale
    G6 the missing-rule register block in contracts/detection-coverage.md equals the oracles' tagged gaps
       (``--write-doc`` regenerates it; a stale block fails, so a new storyline's gaps cannot go unlisted)

    There is deliberately NO survival ratchet here: the per-technique survival baseline belongs to the
    ratchet step. This matrix reports survival; it does not gate on it.

INPUTS. ``out/scenario_matrix.latest.json`` (written by ``scenario_matrix.py --seed 7``, which the gate runs
FIRST) or ``--recompute``. Outputs ``out/technique_matrix.json`` / ``.md``: sorted keys, no timestamps,
byte-identical across runs.

STDLIB + PyYAML. Deterministic.
"""
