def canonical(matrix: dict) -> str:
    return json.dumps(matrix, indent=2, sort_keys=True) + "\n"


def to_markdown(matrix: dict, waivers: dict) -> str:
    L = ["# FENGARDE ATT&CK technique matrix (generated by eval/adversarial/technique_matrix.py)", "",
         f"Seed {matrix['seed']}; storylines: {', '.join(matrix['scenario_list'])}. Harness-measured; "
         "`evaded_declared` is an evasion the rule's own YAML predicts, `evaded_unexpected` is anything else.", "",
         "## Technique x rule-exists / fires-on-storyline / survives-mutation", "",
         "| Technique | Rules | Fires on (baseline) | Survived | Evaded (declared) | Evaded (unexpected) |",
         "|---|---|---|---|---|---|"]
    for key, t in matrix["techniques"].items():
        fires = ", ".join(t["fires_on_storyline"]) or ("companion-only" if t["exercised"] else "NOT EXERCISED")
        L.append(f"| {t['technique']} ({t['framework']}) | {', '.join(t['rules'])} | {fires} | {t['survived']} | "
                 f"{t['evaded_declared']} | {t['evaded_unexpected']} |")
    L += ["", "## Rules not exercised by any storyline (waived, dated)", "", "| Rule | Technique | Waiver |", "|---|---|---|"]
    for stem, rr in matrix["rules"].items():
        if not rr["exercised"]:
            L.append(f"| {stem} | {rr['technique'] or '-'} | {waivers['unexercised'].get(stem, 'NONE')} |")
    L += ["", "## Techniques demonstrated by a storyline with no rule", "",
          "| Technique | Storyline | Step | Reason |", "|---|---|---|---|"]
    for u in matrix["demonstrated_but_undetected"]:
        L.append(f"| {u['technique']} | {u['scenario']} | {u['step']} | {u['reason'][:140]} |")
    L += ["", "## Unexpected evasions (not predicted by the rule's own YAML)", "",
          "| Rule | Storyline | Variant | Step still alerts | Known cause |", "|---|---|---|---|---|"]
    for stem, rr in matrix["rules"].items():
        for sc, cells in rr["survives_mutation"].items():
            for e in cells["evaded_unexpected"]:
                L.append(f"| {stem} | {sc} | {e['variant']} | {e['step_still_alerts']} | "
                         f"{e.get('known_cause', '-')[:120]} |")
    L += ["", "## Observed vs oracle (surfaced, gated by oracle_consistency)", ""]
    L += [f"- {d['scenario']}:{d['step']} {d['rule']}: {d['kind']}" for d in matrix["observed_vs_oracle"]] \
        or ["- none"]
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------------------
# The missing-rule register in contracts/detection-coverage.md (generated, like the evasion-cost block)
# ---------------------------------------------------------------------------
def register_rows(oracles: dict) -> list:
    """One row per (technique, storyline, step) the oracles declare as a coverage gap with an ATT&CK id
    (context steps excluded). Built from the ORACLES, not from the mutation artefact."""
    rows = []
    for name in sorted(oracles):
        for step, pt in sorted((oracles[name].get("detection_points") or {}).items()):
            gap = pt.get("gap") or {}
            if gap.get("no_rule_exists") and not pt.get("context") and gap.get("attack_technique"):
                rows.append({"technique": gap["attack_technique"], "scenario": name, "step": step,
                             "reason": " ".join(str(gap.get("reason", "")).split())})
    return sorted(rows, key=lambda r: (r["technique"], r["scenario"], r["step"]))


def render_register(rows: list) -> str:
    lines = [_REG_BEGIN,
             "Techniques a storyline demonstrates for which its oracle declares `no_rule_exists` (the honest "
             "missing-rule register). Harness-observed: the step's raw record is emitted, parsed where a parser "
             "exists, and NO shipped rule fires. No rule was invented to close any of these; they are product "
             "backlog, not harness defects. A row disappears when a rule starts firing there (the reconciler "
             "reports the stale gap).", "",
             "| Missing rule (ATT&CK technique) | Demonstrated by | Why nothing fires today |", "|---|---|---|"]
    for r in rows:
        name = TECHNIQUE_NAMES.get(r["technique"])
        tech = f"{r['technique']} {name}" if name else r["technique"]
        reason = r["reason"].replace("|", "/")
        lines.append(f"| {tech} | `{r['scenario']}`: `{r['step']}` | {reason} |")
    lines.append(_REG_END)
    return "\n".join(lines)


def doc_block(doc_text: str):
    i, j = doc_text.find(_REG_BEGIN), doc_text.find(_REG_END)
    if i < 0 or j < 0 or j < i:
        return None
    return doc_text[i:j + len(_REG_END)]


def splice_register(doc_text: str, rendered: str) -> str:
    cur = doc_block(doc_text)
    if cur is None:
        raise ValueError("detection-coverage.md has no gap-register markers")
    return doc_text.replace(cur, rendered)


def register_problems(rows: list, doc_text: str) -> list:
    cur = doc_block(doc_text)
    if cur is None:
        return ["G6 contracts/detection-coverage.md has no gap-register block (run technique_matrix.py --write-doc)"]
    if cur != render_register(rows):
        return ["G6 the missing-rule register in contracts/detection-coverage.md is STALE against the oracles' gaps "
                "(run `python eval/adversarial/technique_matrix.py --write-doc`)"]
    return []


def load_artefact(path: Path = ARTEFACT) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def run(artefact: dict, *, rules_dir: Path = RULES_DIR, waivers_path: Path = WAIVERS_PATH,
        check_registry: bool = True) -> tuple:
    """(matrix, waivers, problems) for ``artefact`` against the live registry."""
    import scenario_matrix  # noqa: PLC0415
    import scenario_registry as reg  # noqa: PLC0415
    rules = load_rule_infos(rules_dir)
    oracles = {n: reg.load_oracle(reg.get(n)) for n in artefact["scenarios"]}
    matrix = build(artefact, rules, oracles)
    waivers = load_waivers(waivers_path)
    problems = gate(matrix, waivers,
                    registry_names=[s.name for s in reg.ALL] if check_registry else None,
                    fingerprint=scenario_matrix.inputs_fingerprint() if check_registry else None)
    if check_registry and rules_dir == RULES_DIR:
        import coverage_layer  # noqa: PLC0415
        ids = {r["id"] for r in coverage_layer.load_rules()}
        if ids != {r["id"] for r in rules.values()}:
            problems.append("G4 the rule universe differs from eval/attack/coverage_layer.load_rules()")
    return matrix, waivers, problems


def main(argv: list | None = None) -> int:
    ap = argparse.ArgumentParser(prog="technique_matrix")
    ap.add_argument("--artefact", type=Path, default=ARTEFACT)
    ap.add_argument("--recompute", action="store_true",
                    help="run scenario_matrix itself (seed 7, every storyline) instead of reading the artefact")
    ap.add_argument("--out-dir", type=Path, default=OUT_DIR)
    ap.add_argument("--write-doc", action="store_true",
                    help="regenerate the missing-rule register block in contracts/detection-coverage.md and exit")
    args = ap.parse_args(argv)

    import scenario_registry as reg  # noqa: PLC0415
    all_oracles = {s.name: reg.load_oracle(s) for s in reg.ALL}
    rows = register_rows(all_oracles)
    if args.write_doc:
        COVERAGE_DOC.write_text(splice_register(COVERAGE_DOC.read_text(encoding="utf-8"), render_register(rows)),
                                encoding="utf-8", newline="\n")
        print(f"[OK] wrote the missing-rule register ({len(rows)} rows) to {COVERAGE_DOC}")
        return 0

    if args.recompute:
        import scenario_matrix  # noqa: PLC0415
        artefact = scenario_matrix.run_all(SEED)
    else:
        if not args.artefact.exists():
            print(f"[FAIL] {args.artefact} does not exist: run `python eval/adversarial/scenario_matrix.py "
                  "--seed 7` first (it is gitignored), or pass --recompute")
            return 1
        artefact = load_artefact(args.artefact)
    matrix, waivers, problems = run(artefact)
    problems += register_problems(rows, COVERAGE_DOC.read_text(encoding="utf-8"))
    text = canonical(matrix)
    args.out_dir.mkdir(parents=True, exist_ok=True)
    (args.out_dir / "technique_matrix.json").write_text(text, encoding="utf-8", newline="\n")
    (args.out_dir / "technique_matrix.md").write_text(to_markdown(matrix, waivers), encoding="utf-8", newline="\n")

    n_ex = sum(1 for r in matrix["rules"].values() if r["exercised"])
    print(f"== ATT&CK technique matrix (seed {matrix['seed']}, storylines: {', '.join(matrix['scenario_list'])}) ==")
    print(f"  rules exercised by a storyline: {n_ex}/{len(matrix['rules'])}; "
          f"techniques exercised: {sum(1 for t in matrix['techniques'].values() if t['exercised'])}/"
          f"{len(matrix['techniques'])}")
    print(f"  waived (dated, closed list): {len(waivers['unexercised'])} unexercised, "
          f"{len(waivers['no_technique'])} without a technique")
    print(f"  demonstrated but undetected: {len(matrix['demonstrated_but_undetected'])} "
          f"({', '.join(sorted({u['technique'] for u in matrix['demonstrated_but_undetected']}))})")
    for stem, rr in matrix["rules"].items():
        for sc, cells in rr["survives_mutation"].items():
            if cells["evaded_unexpected"]:
                print(f"  [UNEXPECTED EVASION] {stem} on {sc}: "
                      + ", ".join(e["variant"] for e in cells["evaded_unexpected"]))
    for d in matrix["observed_vs_oracle"]:
        print(f"  [OBSERVED != ORACLE] {d['scenario']}:{d['step']} {d['rule']}: {d['kind']}")
    for p in problems:
        print(f"[FAIL] {p}")
    if problems:
        return 1
    print(f"[OK] technique matrix written to {args.out_dir / 'technique_matrix.json'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
