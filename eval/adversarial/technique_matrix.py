# Gate
# ---------------------------------------------------------------------------
def gate(matrix: dict, waivers: dict, *, registry_names: list | None = None,
         fingerprint: str | None = None, seed: int = SEED) -> list:
    """Problems (empty == green). ``registry_names`` / ``fingerprint`` are None only in unit tests that
    drive the logic on a synthetic world."""
    problems: list = []
    # G1 the artefact is what it claims to be
    if matrix.get("seed") != seed:
        problems.append(f"G1 artefact seed is {matrix.get('seed')!r}, expected {seed} "
                        "(scenario_matrix --seed N writes the same default path)")
    if registry_names is not None and sorted(matrix.get("scenario_list") or []) != sorted(registry_names):
        problems.append(f"G1 artefact covers {sorted(matrix.get('scenario_list') or [])}, the registry has "
                        f"{sorted(registry_names)} (a --scenario run writes the same default path)")
    if fingerprint is not None and matrix.get("inputs_fingerprint") != fingerprint:
        problems.append("G1 artefact inputs_fingerprint differs from the live tree: rules, oracles, parsers or "
                        "harness changed since scenario_matrix last ran -- re-run it")
    rules = matrix["rules"]
    un, nt = waivers["unexercised"], waivers["no_technique"]
    for stem in sorted(set(un) | set(nt)):
        if stem not in rules:
            problems.append(f"G5 waiver for {stem!r} names no shipped rule")
    for table, entries in (("unexercised", un), ("no_technique", nt)):
        for stem, why in sorted(entries.items()):
            if not _DATED.match(str(why or "")):
                problems.append(f"G5 {table} waiver for {stem!r} needs 'YYYY-MM-DD <reason>' (got {why!r})")
    # G2 / G4 / G5 per rule
    for stem, rr in sorted(rules.items()):
        tech = rr["technique"]
        if not tech and stem not in nt:
            problems.append(f"G4 rule {stem} has no mitre: block and is not on the no-technique list")
        if tech and not _TECH_SHAPE.match(str(tech)):
            problems.append(f"G4 rule {stem} declares technique {tech!r}, which is not an ATT&CK/ATLAS id")
        if stem in nt and tech:
            problems.append(f"G5 stale no-technique waiver: {stem} now declares {tech}")
        if rr["exercised"] and stem in un:
            problems.append(f"G5 stale waiver: {stem} IS exercised by a storyline now ({rr['exercised_via']}) -- "
                            "delete its entry from technique_waivers.yaml")
        if not rr["exercised"] and stem not in un:
            what = f"technique {tech}" if tech else "no technique"
            problems.append(f"G2 rule {stem} ({what}) is exercised by no storyline")
    # G3 per technique
    for key, t in sorted(matrix["techniques"].items()):
        if not t["exercised"] and not all(r in un for r in t["rules"]):
            problems.append(f"G3 technique {t['technique']} (declared by {', '.join(t['rules'])}) is exercised by no "
                            "storyline")
    return problems


