"""Render eval/llm_triage/RESULTS.md from the committed results/*.json (every dated file is
listed, newest first). Numbers are read, never hand-copied; the
contract test fails if RESULTS.md differs from this output.

    python eval/llm_triage/render_results.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
RESULTS = HERE / "results"
OUT = HERE / "RESULTS.md"

HEADER = """# WS-5 triage verdict quality: measured results

Generated by `eval/llm_triage/render_results.py` from `eval/llm_triage/results/*.json`.
Do not edit by hand; the contract test (`test_llm_triage_eval.py`) fails on any difference.

## What is and is not measured

- **Cases** (`labelled_cases.json`): alerts the real WS-2 -> WS-4 path raises on repo-owned material.
  `true_positive` = a fired alert on an attack step of a twin storyline or a hard-positive case of the
  curated adversarial corpus; `false_positive` = a fired alert on benign look-alike activity (the
  storylines' decoy builders, the twin's approved-maintenance negative control). Labels come from the
  repo's own oracles/builders, never from a model. Provenance is on every case.
- **Small and imbalanced.** n is a few dozen, the classes are lopsided, and cases are synthetic
  (storyline builders, not production traffic). Read the 95% interval and the majority-class baseline
  before reading the accuracy. A model that answers `malicious` to everything scores the baseline.
- **`needs_review` is an abstention**, not a ground-truth class. An abstention counts as wrong in
  `accuracy`; `accuracy when decisive` excludes it.
- **The stub is score-driven** (`siem.score` >= 80 malicious, >= 60 suspicious, else benign). It never
  reads the event, so its row is a floor to beat, not a quality claim about the product.
- **Severity** is compared with the highest level declared by the rule(s) that fired (`low` for
  false positives): rule-declared, not analyst-judged.
- Every case is sent with `tier=llm` so each exercises `analyze()`; production would route only
  `score >= 60` there (the `llm tier subset` column).
"""


def _f(x, pct=False):
    if x is None:
        return "n/a"
    return f"{x:.1%}" if pct else f"{x}"


def _run_block(r: dict) -> list[str]:
    m = r["metrics"]
    cm = m["confusion_matrix"]
    out = [f"### `{r['label']}`", ""]
    out.append(f"- adapter: `{r['adapter']}`; model: `{r.get('model')}`; timeout: `{r.get('timeout_seconds')}`; "
               f"wall time {r['wall_seconds']} s; adapter fallback counter: `{r.get('adapter_fallback_counter')}`")
    out.append(f"- **n = {m['n']}**  ({m['support']['true_positive']} true_positive, {m['support']['false_positive']} false_positive); "
               f"majority-class baseline accuracy {_f(m['majority_class_baseline_accuracy'], True)}")
    out.append(f"- **accuracy {_f(m['accuracy'], True)}** (95% Wilson {_f(m['accuracy_ci95'][0], True)} to {_f(m['accuracy_ci95'][1], True)}); "
               f"abstain {_f(m['abstain_rate'], True)}; error {_f(m['error_rate'], True)}; "
               f"accuracy when decisive {_f(m['accuracy_when_decisive'], True)} (coverage {_f(m['decisive_coverage'], True)}); "
               f"llm-tier subset n={m['llm_tier_subset']['n']} accuracy {_f(m['llm_tier_subset']['accuracy'], True)}")
    out.append(f"- **engine mix: {m['engine_counts']}; stub share {_f(m['stub_share'], True)}**; "
               f"answered by a model: {m['model_answered']} (accuracy on those: {_f(m['accuracy_on_model_answered'], True)})")
    out.append(f"- severity (vs rule-declared level, {m['severity']['scored']} scored): exact {_f(m['severity']['exact'], True)}, within one level {_f(m['severity']['within_one'], True)}")
    lat = m["latency_ms"]
    out.append(f"- latency per case (ms): mean {lat['mean']}, p50 {lat['p50']}, p95 {lat['p95']}, max {lat['max']}")
    out += ["", "| class | support | predicted | precision | recall | f1 |", "|---|---|---|---|---|---|"]
    for c, v in m["per_class"].items():
        out.append(f"| {c} | {v['support']} | {v['predicted']} | {_f(v['precision'], True)} | {_f(v['recall'], True)} | {_f(v['f1'])} |")
    out += ["", "Confusion matrix (rows = label, columns = prediction):", "",
            "| label \\ predicted | true_positive | false_positive | needs_review | error |", "|---|---|---|---|---|"]
    for c, row in cm.items():
        out.append(f"| {c} | {row['true_positive']} | {row['false_positive']} | {row['needs_review']} | {row['error']} |")
    return out + [""]


def _variants_section(d: dict) -> list[str]:
    sp = d["split"]
    out = ["## Diagnosis: is the poor `qwen2.5:3b` result the prompt, the labels or the model?", "",
           f"Generated from `results/variants.json` (`variants.py`, {d['date']}, model `{d['model']}`). Direct Ollama calls, so "
           "stub share is 0% by construction and no row was a timeout or parse error unless the error column says so.", "",
           f"Protocol: {sp['rule']}. DEV {sp['dev']} cases (variants compared here only; {len(d['fewshot_case_ids'])} are few-shot examples "
           f"and are not scored, leaving {d['dev_n_scored']}), HOLDOUT {sp['holdout']} cases "
           f"({sp['holdout_by_label']['true_positive']} true_positive, {sp['holdout_by_label']['false_positive']} false_positive: "
           "the false-positive numbers rest on a handful of cases). The variant picked on DEV (best accuracy) was run once on HOLDOUT.", "",
           "**Label ceiling.** Alerts are single events plus rule titles. In 9 of 33 distinct (rule, source) signatures a true and a "
           "false positive share the same rule and source (e.g. a scanner decoy and the attacker's scan are the same ASA deny line "
           "from different, equally private addresses), so a verdict from (rule, source) alone is capped at 44/54 = 81.5%, the "
           "always-malicious baseline. Telling them apart needs entity/baseline context the model is not given.", "",
           "### DEV (scored cases only)", "",
           "| variant | n | accuracy | abstain | error | TP recall | TP precision | FP recall | FP precision | p50 latency ms |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for n, r in d["dev"].items():
        m = r["metrics"]; t, f = m["per_class"]["true_positive"], m["per_class"]["false_positive"]
        out.append(f"| {n}: {r['note']} | {m['n']} | {_f(m['accuracy'], True)} | {_f(m['abstain_rate'], True)} | {_f(m['error_rate'], True)} | "
                   f"{_f(t['recall'], True)} | {_f(t['precision'], True)} | {_f(f['recall'], True)} | {_f(f['precision'], True)} | {m['latency_ms']['p50']} |")
    out += ["", f"### HOLDOUT (picked on DEV: `{d['picked_on_dev']}`)", "",
            "| variant | n | accuracy (95% Wilson) | abstain | TP recall | TP precision | FP recall | FP precision | always-malicious baseline |",
            "|---|---|---|---|---|---|---|---|---|"]
    for n, r in d["holdout"].items():
        m = r["metrics"]; t, f = m["per_class"]["true_positive"], m["per_class"]["false_positive"]
        out.append(f"| {n} | {m['n']} | {_f(m['accuracy'], True)} ({_f(m['accuracy_ci95'][0], True)} to {_f(m['accuracy_ci95'][1], True)}) | "
                   f"{_f(m['abstain_rate'], True)} | {_f(t['recall'], True)} | {_f(t['precision'], True)} | {_f(f['recall'], True)} | "
                   f"{_f(f['precision'], True)} | {_f(m['majority_class_baseline_accuracy'], True)} |")
    out += ["", "Reading: " + d.get("reading", ""), ""]
    return out


def render(results_dir: Path = RESULTS) -> str:
    files = sorted((f for f in results_dir.glob("*.json") if f.name != "variants.json"), reverse=True)
    lines = [HEADER]
    if (results_dir / "variants.json").exists():
        lines += _variants_section(json.loads((results_dir / "variants.json").read_text(encoding="utf-8")))
    if not files:
        lines.append("No results committed yet.\n")
    for f in files:
        d = json.loads(f.read_text(encoding="utf-8"))
        hw = d["hardware"]
        lines += [f"## Run {d['date']}  (`results/{f.name}`)", "",
                  f"- hardware: {hw['platform']}; {hw['cpu']}; {hw['logical_cpus']} logical CPUs; {hw['ram_gb']} GB RAM; GPU: {hw['gpu']}",
                  f"- labelled set sha256 `{d['labelled_set_sha256'][:16]}...`, counts {d['labelled_set_counts']}",
                  f"- **real-model run: {'BLOCKED. ' + d['ollama_blocked'] if d.get('ollama_blocked') else 'performed (see per-model blocks)'}**", ""]
        if d.get("notes"):
            lines += [f"- notes: {d['notes']}", ""]
        for r in d["runs"]:
            lines += _run_block(r)
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    OUT.write_text(render(), encoding="utf-8", newline="\n")
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
